    // Synthetic (inline, not a fixture): the archived-livestream case — YouTube sets
    // `videoDetails.isLiveContent = true` forever once a video has ever been live, but the
    // specific `isLive` flips to `false` once the broadcast ends. The parser must prefer `isLive`
    // over the sticky `isLiveContent`.
    // Deviation from the fix-round request: written with `isLive` explicitly `false`, not absent.
    // With the specified fallback (`isLive ?? isLiveContent ?? false`), an *absent* isLive key
    // falls through to `isLiveContent` and correctly yields `true` per that formula — only an
    // explicit `isLive: false` exercises the "no longer live" case this fix targets.
    @Test func archivedLivestreamPrefersIsLiveOverStickyIsLiveContent() throws {
        let body = Data(
            """
            {"playabilityStatus": {"status": "OK"}, "videoDetails": {"isLive": false, "isLiveContent": true}}
            """.utf8)
        let result = try parser.parse(body).playability
        switch result {
        case .ok(let streaming):
            #expect(!streaming.isLive)
        default:
            Issue.record("expected .ok, got \(result)")
        }
    }

