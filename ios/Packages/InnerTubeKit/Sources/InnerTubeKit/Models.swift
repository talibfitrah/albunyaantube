import Foundation

/// A caption/subtitle track discovered on a stream (`extraction.md` §4).
public struct CaptionTrack: Sendable, Equatable {
    public var url: URL
    public var languageCode: String
    public var languageName: String
    public var isAutoGenerated: Bool

    public init(url: URL, languageCode: String, languageName: String, isAutoGenerated: Bool) {
        self.url = url
        self.languageCode = languageCode
        self.languageName = languageName
        self.isAutoGenerated = isAutoGenerated
    }
}

/// The playable result of resolving a videoId (spec §9).
public enum ResolvedStream: Sendable {
    /// `synthetic` (spec R13): the `tv_samsung` HD upgrade's model, played through `SyntheticHLSLoader` on
    /// `fitrah-hls://`. nil for every native manifest.
    case hls(url: URL, isLive: Bool, audioOnlyURL: URL?, captionTracks: [CaptionTrack], synthetic: SyntheticHLS? = nil)
    case progressive(url: URL, label: String)
    // No `openInYouTube` case (owner directive 2026-08-27: no redirect or hand-off to YouTube) and
    // no `embed` case (owner directive 2026-10-14: no YouTube player of any kind). The ladder's
    // floor is the progressive stream; anything below it is an `ExtractionError`.
}

extension ResolvedStream {
    /// The synthesized HLS behind a `tv_samsung` stream; nil for every other stream.
    public var synthetic: SyntheticHLS? {
        if case .hls(_, _, _, _, let synthetic) = self { return synthetic }
        return nil
    }
}

/// The InnerTube client family a resolve was performed under. The `userAgent`
/// that minted a stream's URLs must be reused on segment fetches or googlevideo
/// 403s (`StreamModels.kt:110-119`) — load-bearing even though a Task-1 probe
/// found no immediate mismatch failure.
public enum ClientFamily: Sendable {
    case visionos
    case android
    case web
    /// The tv_samsung TVHTML5 client of the HD upgrade (spec R3).
    case tvSamsung

    /// The `context.client.clientName` value this family's `ClientContext` must carry
    /// (`remote-config-default.json`) — guards against mixing a family with the wrong
    /// context under one visitor (§6.3).
    var expectedClientName: String {
        switch self {
        case .visionos: return "VISIONOS"
        case .android: return "ANDROID"
        case .web: return "WEB"
        case .tvSamsung: return "TVHTML5"
        }
    }
}

/// A resolved stream plus the context needed to play/expire it.
public struct Resolved: Sendable {
    public var stream: ResolvedStream
    public var client: ClientFamily
    public var userAgent: String
    public var resolvedAt: Date
    public var expiresAt: Date?

    public init(stream: ResolvedStream, client: ClientFamily, userAgent: String, resolvedAt: Date, expiresAt: Date?) {
        self.stream = stream
        self.client = client
        self.userAgent = userAgent
        self.resolvedAt = resolvedAt
        self.expiresAt = expiresAt
    }

    public func isExpired(now: Date) -> Bool {
        guard let expiresAt else { return false }
        return expiresAt <= now
    }
}

/// Errors surfaced by the resolve ladder. `transport` carries a `String`
/// (not the underlying `Error`) so the whole enum stays `Equatable`.
public enum ExtractionError: Error, Sendable, Equatable {
    case invalidVideoId
    case unavailable(videoId: String)
    case ageRestricted
    case geoBlocked
    case `private`
    case removed
    case liveOffline(startsAt: Date?)
    case botCheck
    /// The persisted escalating cooldown is active; no rung ran and no network call was made.
    /// `until` is when the backoff elapses (§6.3). Terminal for this resolve — retry after `until`.
    case cooldown(until: Date)
    case allRungsFailed
    case cancelled
    case transport(String)

    /// True for errors that will never succeed on retry (ruling 14).
    public var terminal: Bool {
        switch self {
        case .ageRestricted, .geoBlocked, .private, .removed, .unavailable, .liveOffline, .cooldown:
            return true
        case .invalidVideoId, .botCheck, .allRungsFailed, .cancelled, .transport:
            return false
        }
    }
}

/// The two resolve lanes (ruling 16).
public enum Purpose: Sendable {
    case player
    case prefetch
    /// A cast's own muxed walk (`requiresMuxed`). Scoped to the cast: a bot check there fails the
    /// cast only and never records the global cooldown -- from the phone's usual `.hls` the android
    /// rung is untried, and a trip would lock out the phone's WORKING rung-1 playback for up to 5 minutes.
    case cast
}
